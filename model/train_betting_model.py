    def _ensure_pre_game_team_metrics(self, df):
        df = df.sort_values('game_date').copy()
        for side in ('home','away'):
            wpct_pre = []; pf_pre = []; pa_pre = []; pd_pre = []
            totals = {}
            for _, r in df.iterrows():
                t = self._normalize_team(r[f'{side}_team'])
                if t not in totals:
                    totals[t] = {'gp':0,'w':0,'pf_sum':0.0,'pa_sum':0.0}
                cur = totals[t]; gp = cur['gp']
                pfm = cur['pf_sum']/gp if gp>0 else 20.0
                pam = cur['pa_sum']/gp if gp>0 else 20.0
                wpct_pre.append((cur['w']/gp) if gp>0 else 0.5)
                pf_pre.append(pfm); pa_pre.append(pam); pd_pre.append(pfm-pam)
                pf = float(r['home_score'] if side=='home' else r['away_score'])
                pa = float(r['away_score'] if side=='home' else r['home_score'])
                win = 1 if pf > pa else 0
                cur['gp'] += 1; cur['w'] += win; cur['pf_sum'] += pf; cur['pa_sum'] += pa
            df[f'{side}_wpct_pre'] = wpct_pre
            df[f'{side}_pf_pre']   = pf_pre
            df[f'{side}_pa_pre']   = pa_pre
            df[f'{side}_pd_pre']   = pd_pre
        return df

    def _add_simple_momentum(self, df):
        print("Adding momentum features...")
        df['home_form'] = 0.5; df['home_streak'] = 0
        df['away_form'] = 0.5; df['away_streak'] = 0

        team_records = {}
        all_teams = pd.concat([df['home_team'], df['away_team']]).astype(str).unique()
        for team in all_teams:
            q = """
            SELECT game_date,
                   CASE WHEN home_team = ? THEN 
                        CASE WHEN home_score > away_score THEN 1 ELSE 0 END
                   ELSE CASE WHEN away_score > home_score THEN 1 ELSE 0 END
                   END as won
            FROM games 
            WHERE (home_team = ? OR away_team = ?)
              AND home_score IS NOT NULL AND away_score IS NOT NULL
            ORDER BY game_date DESC
            """
            try:
                tg = pd.read_sql_query(q, self.conn, params=[team, team, team])
                tg['game_date'] = pd.to_datetime(tg['game_date'])
                team_records[team] = tg
            except:
                team_records[team] = pd.DataFrame(columns=['game_date','won'])

        for i, r in df.iterrows():
            if i % 200 == 0:
                print(f"  Processing momentum for game {i}/{len(df)}")
            gd = pd.to_datetime(r['game_date'])
            for side in ('home','away'):
                t = str(r[f'{side}_team'])
                rec = team_records.get(t)
                if rec is not None and not rec.empty:
                    recent = rec[rec['game_date'] < gd].head(5)
                    if len(recent) >= 2:
                        form = float(recent['won'].mean())
                        streak = 0
                        if len(recent) > 0:
                            last = int(recent['won'].iloc[0])
                            for w in recent['won']:
                                if int(w) == last: streak += 1
                                else: break
                            if last == 0: streak = -streak
                    else:
                        form, streak = 0.5, 0
                else:
                    form, streak = 0.5, 0
                df.at[i, f'{side}_form'] = form
                df.at[i, f'{side}_streak'] = streak
        return df

    def _add_matchup_features(self, df):
        print("Adding matchup features...")
        divisions = {
            'AFC_EAST':['BUF','MIA','NE','NYJ'],'AFC_NORTH':['BAL','CIN','CLE','PIT'],
            'AFC_SOUTH':['HOU','IND','JAX','TEN'],'AFC_WEST':['DEN','KC','LV','LAC'],
            'NFC_EAST':['DAL','NYG','PHI','WAS'],'NFC_NORTH':['CHI','DET','GB','MIN'],
            'NFC_SOUTH':['ATL','CAR','NO','TB'],'NFC_WEST':['ARI','LAR','SF','SEA']
        }
        t2d = {}
        for d, teams in divisions.items():
            for t in teams:
                t2d[t] = d; t2d[self._normalize_team(t)] = d

        df['same_division'] = df.apply(
            lambda r: 1 if t2d.get(self._normalize_team(r['home_team'])) ==
                           t2d.get(self._normalize_team(r['away_team'])) else 0, axis=1)
        df['same_conference'] = df.apply(
            lambda r: 1 if (t2d.get(self._normalize_team(r['home_team']), '')[:3] ==
                            t2d.get(self._normalize_team(r['away_team']), '')[:3]) else 0, axis=1)
        return df

    def _add_rest_features(self, df):
        df = df.sort_values('game_date').copy()
        last_played = {}; home_rest=[]; away_rest=[]
        for _, r in df.iterrows():
            gd = pd.to_datetime(r['game_date'])
            ht = self._normalize_team(r['home_team'])
            at = self._normalize_team(r['away_team'])
            hr = (gd - last_played[ht]).days if ht in last_played else 7
            ar = (gd - last_played[at]).days if at in last_played else 7
            home_rest.append(hr); away_rest.append(ar)
            last_played[ht] = gd; last_played[at] = gd
        df['home_rest_days'] = home_rest
        df['away_rest_days'] = away_rest
        df['rest_diff'] = df['home_rest_days'] - df['away_rest_days']
        return df

    def engineer_core_features(self, df):
        print("Engineering core features...")
        df = df.fillna(0)
        df['home_power_pre'] = df['home_pd_pre']
        df['away_power_pre'] = df['away_pd_pre']
        df['power_diff']   = df['home_power_pre'] - df['away_power_pre']
        df['win_pct_diff'] = df['home_wpct_pre']  - df['away_wpct_pre']
        df['offense_diff'] = df['home_pf_pre']   - df['away_pf_pre']
        df['home_def_str'] = -df['home_pa_pre']
        df['away_def_str'] = -df['away_pa_pre']
        df['defense_diff'] = df['home_def_str'] - df['away_def_str']
        if 'home_form' in df.columns:
            df['form_diff'] = df['home_form'] - df['away_form']
            df['streak_diff'] = df['home_streak'] - df['away_streak']
        df['home_field_advantage'] = 2.5
        df['late_season'] = (df['month'] >= 11).astype(int)
        df['prime_time'] = ((df['day_of_week'] == 0) | (df['day_of_week'] == 1)).astype(int)
        df['both_good'] = ((df['home_power_pre'] > 2) & (df['away_power_pre'] > 2)).astype(int)
        df['mismatch_game'] = (abs(df['power_diff']) > 5).astype(int)
        df['power_x_form'] = df['power_diff'] * df.get('form_diff', 0)
        df['strength_disparity'] = abs(df['home_power_pre'] - df['away_power_pre'])
        return df

    def select_core_features(self, df):
        drop = ['game_id','home_team','away_team','home_score','away_score','game_date','season','home_win']
        feats = [c for c in df.columns if c not in drop]
        for c in feats:
            df[c] = pd.to_numeric(df[c], errors='coerce')
        df[feats] = df[feats].fillna(0)
        feats = [c for c in feats if df[c].nunique() > 1]
        print(f"Selected {len(feats)} features for training")
        print("Key features:", [c for c in feats if ('diff' in c or 'power' in c)][:10])
        return feats

    def train_calibrated_models(self, df):
        print("Training calibrated models...")
        feats = self.select_core_features(df)
        d = df.sort_values('game_date').reset_index(drop=True)
        seasons = sorted(d['season'].dropna().unique().tolist())

        use_season = len(seasons) >= 3
        if use_season:
            train_mask = d['season'].isin(seasons[:-2])
            cal_mask   = d['season'].isin([seasons[-2]])
            test_mask  = d['season'].isin([seasons[-1]])
            if d.loc[test_mask].shape[0] < 100:
                use_season = False
        if not use_season:
            n = len(d); train_end = int(n*0.6); cal_end = int(n*0.8)
            train_mask = d.index < train_end
            cal_mask   = (d.index >= train_end) & (d.index < cal_end)
            test_mask  = d.index >= cal_end

        X_train, y_train = d.loc[train_mask, feats], d.loc[train_mask, 'home_win']
        X_cal,   y_cal   = d.loc[cal_mask, feats],   d.loc[cal_mask, 'home_win']
        X_test,  y_test  = d.loc[test_mask, feats],  d.loc[test_mask, 'home_win']

        print(f"Train: {len(X_train)}, Cal: {len(X_cal)}, Test: {len(X_test)}")

        models = {
            'LogisticRegression': LogisticRegression(C=0.5, max_iter=1000, random_state=42),
            'RandomForest': RandomForestClassifier(
                n_estimators=250, max_depth=8, min_samples_split=40, min_samples_leaf=12, random_state=42)
        }

        results = {}; best = -1e9
        X_tr_s = self.scaler.fit_transform(X_train)
        X_ca_s = self.scaler.transform(X_cal)
        X_te_s = self.scaler.transform(X_test)

        for name, base in models.items():
            print(f"\nTraining {name}...")
            if name == 'LogisticRegression':
                base.fit(X_tr_s, y_train)
                calibrated = CalibratedClassifierCV(base, method='sigmoid', cv='prefit')
                calibrated.fit(X_ca_s, y_cal)
                proba = calibrated.predict_proba(X_te_s)[:,1]
                uses_scaled = True
            else:
                base.fit(X_train, y_train)
                calibrated = CalibratedClassifierCV(base, method='sigmoid', cv='prefit')
                calibrated.fit(X_cal, y_cal)
                proba = calibrated.predict_proba(X_test)[:,1]
                uses_scaled = False

            pred = (proba > 0.5).astype(int)
            acc = accuracy_score(y_test, pred)
            auc = roc_auc_score(y_test, proba)
            ll  = log_loss(y_test, proba)
            pt, pp = calibration_curve(y_test, proba, n_bins=5)
            cal_err = float(np.mean(np.abs(pt - pp)))
            score = auc - 2*cal_err - 0.5*ll

            results[name] = {'model': calibrated,'accuracy':acc,'auc':auc,'logloss':ll,
                             'calibration_error':cal_err,'betting_score':score}
            print(f"  Accuracy: {acc:.3f}")
            print(f"  AUC: {auc:.3f}")
            print(f"  LogLoss: {ll:.3f}")
            print(f"  Calibration Error: {cal_err:.3f}")
            print(f"  Betting Score: {score:.3f}")

            if score > best:
                best = score
                self.best_model = calibrated
                self.feature_cols = feats
                self.uses_scaled = uses_scaled

            if hasattr(base, 'feature_importances_'):
                imp = (pd.DataFrame({'feature': feats, 'importance': base.feature_importances_})
                         .sort_values('importance', ascending=False))
                self.feature_importance[name] = imp
                print("\nTop 5 features for RandomForest:")
                print(imp.head())

        if not hasattr(self, 'best_model'):
            raise RuntimeError("No models trained successfully!")
        self.model_metrics = results
        print(f"\nBest model selected with betting score: {best:.3f}")
        return results

