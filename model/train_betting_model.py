    def _to_decimal_odds(self, odds_value):
        """Convert various odds formats to decimal"""
        try:
            odds = float(odds_value)
            
            # If already decimal (between 1.01 and 50)
            if 1.01 <= odds <= 50:
                return odds
            
            # American odds
            if odds >= 100:
                return 1 + (odds / 100)
            elif odds <= -100:
                return 1 + (100 / abs(odds))
            else:
                return 1.91  # Default -110
                
        except:
            return 1.91  # Default fallback

    def kelly_bet_size(self, win_prob, decimal_odds):
        """Calculate Kelly Criterion bet size"""
        if win_prob <= 0 or decimal_odds <= 1:
            return 0
        
        b = decimal_odds - 1  # Net odds
        p = win_prob
        q = 1 - win_prob
        
        if p * b > q:
            return (p * b - q) / b
        return 0

    def generate_confidence_score(self, prob):
        """Generate confidence score based on probability distance from 0.5"""
        distance = abs(prob - 0.5)
        return min(0.95, max(0.5, 0.5 + 1.6 * distance))

    def backtest_realistic(self, df):
        """Fallback backtest with simulated odds (original method)"""
        print("\nRunning fallback backtest with -110 odds...")
        
        d = df.sort_values('game_date').reset_index(drop=True)
        test_start = int(len(d)*0.8)
        dtest = d.iloc[test_start:].copy()
        
        bankroll = 1000.0
        bets = wins = 0
        pnl = 0.0
        
        for _, g in dtest.iterrows():
            x = g[self.feature_cols].values.reshape(1, -1)
            if self.uses_scaled: x = self.scaler.transform(x)
            p_home = float(self.best_model.predict_proba(x)[0,1])
            p_away = 1.0 - p_home
            
            # Use -110 odds (1.91 decimal)
            mkt_prob = 0.5238  # Implied prob of -110
            edge_home = p_home - mkt_prob
            edge_away = p_away - mkt_prob
            conf = self.generate_confidence_score(p_home)
            
            if max(edge_home, edge_away) >= MIN_EDGE and conf >= MIN_CONF:
                bet_size = MAX_BET_PCT * bankroll
                if edge_home >= edge_away:
                    won = (g['home_win'] == 1)
                else:
                    won = (g['home_win'] == 0)
                
                profit = bet_size * 0.91 if won else -bet_size  # -110 payout
                bankroll += profit
                pnl += profit
                bets += 1
                wins += (1 if won else 0)
        
        if bets > 0:
            win_rate = wins / bets
            roi = (pnl / (bets * MAX_BET_PCT * 1000)) * 100
            print(f"  Fallback results: {bets} bets, {win_rate:.1%} win rate, {roi:.1f}% ROI")

