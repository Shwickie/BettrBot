    def _normalize_team(self, name):
        if name is None: return None
        s = str(name).strip()
        if s in self.team_name_map: return self.team_name_map[s]
        if s.upper() in self.team_name_map: return self.team_name_map[s.upper()]
        if len(s) <= 3: return s.upper()
        for k, ab in self.team_name_map.items():
            if s.lower() in k.lower() or k.lower() in s.lower():
                return ab
        return s[:3].upper()

    def build_core_dataset(self):
        print("Building core dataset with verified features...")
        q = """
        SELECT 
            g.game_id, g.home_team, g.away_team,
            g.home_score, g.away_score, g.game_date,
            CASE WHEN g.home_score > g.away_score THEN 1 ELSE 0 END AS home_win,
            CAST(strftime('%Y', g.game_date) AS INTEGER) AS season,
            CAST(strftime('%m', g.game_date) AS INTEGER) AS month,
            CAST(strftime('%w', g.game_date) AS INTEGER) AS day_of_week
        FROM games g
        WHERE g.home_score IS NOT NULL AND g.away_score IS NOT NULL
          AND g.game_date > date('now', '-3 years')
        ORDER BY g.game_date
        """
        df = pd.read_sql_query(q, self.conn)
        print(f"Base dataset: {len(df)} games")
        if len(df) < 100:
            raise RuntimeError("Too little data.")

        df = self._ensure_pre_game_team_metrics(df)
        df = self._add_simple_momentum(df)
        df = self._add_matchup_features(df)
        df = self._add_rest_features(df)

        print(f"Final dataset: {len(df)} games, {len(df.columns)} features")
        return df

    # Train only on data BEFORE the test period
    def proper_time_split(self, df):
        df_sorted = df.sort_values('game_date')
        # Use 80% for training, 20% for testing
        # But ensure NO data leakage from future to past
        split_date = df_sorted['game_date'].quantile(0.8)
        train = df_sorted[df_sorted['game_date'] < split_date]
        test = df_sorted[df_sorted['game_date'] >= split_date]
        return train, test

